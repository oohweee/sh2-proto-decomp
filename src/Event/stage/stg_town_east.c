        vwGetViewPosition(campos);
        for (i = 0; i < 4; i++) {
            CB_Tonnel[i * 4][2] = 6000.0f + campos[2];
        }
        env[0].ui32[0] = 0x10000004;
        env[0].ui32[1] = 0;
        env[0].ui32[2] = 0x11000000;
        env[0].ui32[3] = 0x50000004;
