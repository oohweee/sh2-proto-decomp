        env[3].ul64[0] = 0x58002;
        env[4].ul64[1] = 0x4E;
        env[4].ul64[0] = 0x13A0001C0;
        env[5].ui32[0] = 0x70000000;
        env[5].ui32[1] = 0;
        env[5].ul64[1] = 0;
        for (i = 0; i < 1; i++) {
            MakeScissorPacket(CB_Tonnel[i * 16], (void **)&kickbuf, (void **)&scikickbuf, 0, 0xC, 4);
        }
        kickbuf->ul128 = 0;
        kickbuf->ui32[0] = 0x70000000;
        scikickbuf->ul128 = 0;
        scikickbuf->ui32[0] = 0x70000002;
        scikickbuf->ui32[3] = 0x50000002;
