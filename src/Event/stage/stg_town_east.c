/*
 * Game flag n: bit n & 31 of game_flag.flag[n >> 5]. Names invented (after the GAME_FLAG macros
 * of other files); the index form is this file's own (EvProgLookMemoFalled clears flag
 * 0x33 + 2 * i). Matching: inline functions, not macros: the code is the same, but the calls
 * leave the compiler state that gives CB_1stMoster_FogHosei its float-constant order
 * (docs/toolchain.md, "Root cause").
 */
inline int GAME_FLAG(int n) {
    return (game_flag.flag[n >> 5] >> (n & 31)) & 1;
}

inline void GAME_FLAG_ON(int n) {
    game_flag.flag[n >> 5] |= 1 << (n & 31);
}

inline void GAME_FLAG_OFF(int n) {
    game_flag.flag[n >> 5] &= ~(1 << (n & 31));
}


