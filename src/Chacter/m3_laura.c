static int HumanLAUInit() { /* Matching: K&R definition; called with arguments it ignores (the DWARF shows none). */
    return 0;
}

static void HumanLAUFunction(struct SubCharacter *this) {
    struct _AnimeInfo *aip;
    short id;

    switch (this->step) {
    case 0:
        id = shCharacterGetModelID(this);
        if (id == 0x104) {
            HumanLAUInit(this);
            aip = (struct _AnimeInfo *)&laura_anim[1];
            shCharacterAnimeSet(this, 0, 0, aip, (int)shCharacterGetAnimeAdrForDrama(this, 1));
        }
        this->step++;
    case 1:
        break;
    }
}

/** Installs the LAU update function on a sub-character. @param scp the character. */
void shCharacterSetHumanLAULow(struct SubCharacter *scp) {
    shCharacterSetFunction(scp, HumanLAUFunction);
}

/**
 * Plays drama (event) animation @p anime_id and its cluster animation on a LAU model.
 * @param scp the character. @param anime_id animation ID in the drama table.
 * @return 0, or -1 if @p scp isn't a LAU model.
 */
int shCharacterHumanLAUAnimeSet(struct SubCharacter *scp, int anime_id) {
    struct _AnimeInfo *aip;

    SCAnimeTypeSwitch(scp, 0);
    if (shCharacterGetModelID(scp) == 0x104) {
        aip = (struct _AnimeInfo *)&laura_anim[anime_id - 0x9C4];
        shCharacterAnimeSet(scp, 0, 2, aip,
                            dlaura_anime_adr_list[anime_id - 0x9C4] +
                                (int)shCharacterGetAnimeAdrForDrama(scp, anime_id - 0x9C4));
        shCharacterClusterAnimeSet(scp, dlaura_clani_adr_list[anime_id - 0x9C4] +
                                            (int)shCharacterGetClusterAnimeAdr(scp));
        return 0;
    }
    return -1;
}

/**
 * Plays gameplay animation @p anime_id on a LAU model.
 * @param scp the character. @param anime_id animation ID in the gameplay table.
 * @return 0, or -1 if @p scp isn't a LAU model.
 */
int shCharacterHumanLAUAnimeSetP(struct SubCharacter *scp, int anime_id) {
    struct _AnimeInfo *aip;

    SCAnimeTypeSwitch(scp, 1);
    if (shCharacterGetModelID(scp) == 0x104) {
        aip = (struct _AnimeInfo *)&plaura_anim[anime_id - 0xB54];
        shCharacterAnimeSet(scp, 0, 0, aip, (int)shCharacterGetAnimeAdrForPlay(scp));
        return 0;
    }
    return -1;
}
