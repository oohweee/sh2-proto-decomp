static void HumanDJMSFunction(struct SubCharacter *this) {
    struct _AnimeInfo *aip;

    switch (this->step) {
    case 0:
        HumanDJMSInit(this);
        aip = (struct _AnimeInfo *)&djames_anim[1];
        shCharacterAnimeSet(this, 0, 0, aip, (int)shCharacterGetAnimeAdrForDrama(this, 1));
        this->step++;
        break;
    case 1:
        DemoJamesCheckModelParts(this);
        DemoPlayerSetHeight(this);
        break;
    }
}

/** Sets a drama character's ground height and normal from the floor below it. @param this the character. */
void DemoPlayerSetHeight(struct SubCharacter *this) {
    float sp[4];
    float ep[4];
    struct _CL_VHIT_RESULT floor;
    /* Matching: called without a prototype in the original (arguments passed unconverted). */
    void clCheckHitEyesOnlyFloor();

    vcopy_dst_first(sp, (float *)&this->pos);
    vcopy_dst_first(ep, sp);
    sp[1] -= 250.0f;
    ep[1] += 1500.0f;
    clCheckHitEyesOnlyFloor(&floor, this, sp, ep);
    if (floor.kind == 1) {
        this->grnd_height = floor.hobj.wall.cp[1];
        *(struct FVEC *)this->grnd_normal = *(struct FVEC *)floor.hobj.wall.nl;
    } else {
        this->grnd_normal[0] = this->grnd_normal[1] = this->grnd_normal[2] = this->grnd_normal[3] =
            this->grnd_height = 0.0f;
    }
}

/** Installs the DJMS update function. @param scp the character. */
void shCharacterSetHumanDJMSLow(struct SubCharacter *scp) {
    shCharacterSetFunction(scp, HumanDJMSFunction);
}

/**
 * Plays drama animation @p anime_id and its cluster animation on a James model (0x102/0x103).
 * @param scp the character. @param anime_id animation ID in the drama table.
 * @return 0, or -1 if @p scp isn't a James model.
 */
int shCharacterHumanDJAMESAnimeSet(struct SubCharacter *scp, int anime_id) {
    short id;
    struct _AnimeInfo *aip;

    id = shCharacterGetModelID(scp);
    if (id == 0x103 || id == 0x102) {
        aip = (struct _AnimeInfo *)&djames_anim[anime_id - 0x3E8];
        shCharacterAnimeSet(scp, 0, 2, aip,
                            djames_anime_adr_list[anime_id - 0x3E8] +
                                (int)shCharacterGetAnimeAdrForDrama(scp, anime_id - 0x3E8));
        shCharacterClusterAnimeSet(scp, djames_clani_adr_list[anime_id - 0x3E8] +
                                            (int)shCharacterGetClusterAnimeAdr(scp));
        return 0;
    }
    return -1;
}

static int HumanRDJMSInit(struct SubCharacter *scp) {
    SCAnimeTypeSwitch(scp, 0);
    scp->model_type = 1;
    switch (sh2jms.room_name_now) {
    case 1:
        mirror_mode = 0;
        wall_pos = -20000.0f;
        break;
    case 0x24:
        mirror_mode = 2;
        wall_pos = -99995.0f;
        break;
    }
    return 0;
}

