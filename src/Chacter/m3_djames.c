static void DemoJamesCheckModelParts(struct SubCharacter *this) {
    int rhand;
    int lhand;
    int light;

    if ((sh2jms.player->status & 0x8000) || !((item.flag[0] >> 15) & 1)) {
        light = 0;
    } else {
        light = 0x15;
    }
    if (this->kind == 0x103) {
        lhand = 0;
        rhand = 0;
    } else {
        lhand = 0;
        switch (sh2jms.weapon) {
        case 0:
            rhand = 3;
            break;
        case 1:
            rhand = 7;
            break;
        case 2:
        case 3:
            rhand = 8;
            break;
        case 4:
            rhand = 0xB;
            break;
        case 5:
            rhand = 0xA;
            break;
        case 6:
            rhand = 9;
            break;
        case 8:
            rhand = 0xC;
            break;
        case 7:
            rhand = 0xD;
            break;
        }
    }
    sh2gfw_Set_JMSequip(this, lhand, rhand, light);
}

