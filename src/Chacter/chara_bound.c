/** Returns the bounding radius of character @p chara_id, or 2500 if it isn't in the table. */
float CharaGetBoundR(int chara_id) {
    int i;
    int n;

    n = CharaBoundTblNum();
    for (i = 0; i < n; i++) {
        if (chara_id == chara_bound_tbl[i].chara_id) {
            return chara_bound_tbl[i].r;
        }
    }
    return 2500.0f;
}
